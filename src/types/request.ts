import type {RecordingAction, RecordingAudio, RecordingDurationMode, RecordingOutputOptions, RecordingTrigger} from "./recording.js";

export type ColorSchemeType = 'light' | 'dark';
export type PdfUnit = 'px' | 'in' | 'cm' | 'mm';
export type MediaType = 'print' | 'screen';
export type RenderImageFormat = 'png' | 'jpg' | 'webp' | 'pdf';

export enum RequestOverrideResourceType {
    Beacon = 'beacon',
    Document = 'document',
    Stylesheet = 'stylesheet',
    Image = 'image',
    ImageSet = 'image_set',
    Media = 'media',
    Font = 'font',
    Script = 'script',
    TextTrack = 'text_track',
    Xhr = 'xhr',
    Fetch = 'fetch',
    EventSource = 'event_source',
    Manifest = 'manifest',
    Ping = 'ping',
    Img = 'img',
    Other = 'other',
}

export enum RequestOverrideAction {
    Block = 'block',
}

export interface RequestOverride {
    action: RequestOverrideAction.Block;
    url?: string;
    resource_types?: RequestOverrideResourceType[];
}

export interface PdfValueWithUnits {
    value: number;
    unit: PdfUnit;
}

export type PdfValueInput = number | PdfValueWithUnits;


/**
 * Represents the margins of a PDF document.
 *
 * This interface defines the margin values for a PDF, allowing
 * customization of the top, right, bottom, and left spacing in the document.
 * Each margin value is expected to be provided using the `PdfValueInput` type.
 */
export interface PdfMargins {
    top: PdfValueInput;
    right: PdfValueInput;
    bottom: PdfValueInput;
    left: PdfValueInput;
}

export class PDFOptions {
    /**
     * Whether background graphics should be printed in the PDF output.
     */
    print_background?: boolean;

    /**
     * The scale factor applied when generating the PDF output.
     */
    scale?: number;

    /**
     * Gets or sets the margins to be applied to the PDF output.
     * Specifies the top, right, bottom, and left margins.
     */
    margins?: PdfMargins;

    /**
     * The height of the PDF page (e.g., 8.5, '11in', '297mm').
     */
    page_height?: PdfValueInput;

    /**
     * The width of the PDF page (e.g., 11, '8.5in', '210mm').
     */
    page_width?: PdfValueInput;

    constructor(init?: Partial<PDFOptions>) {
        Object.assign(this, init);
    }


}


export abstract class BaseCreateImageRequest {
    /**
     * The file format used in the URL returned by the image creation request.
     *
     * This option is supported for HTML/CSS and URL requests, including batch
     * requests. It only changes the extension of the initially returned URL;
     * it does not change the stored image definition or prevent the image from
     * being rendered in another supported format. When omitted, the API
     * returns its default image URL.
     *
     * @see https://docs.htmlcsstoimage.com/getting-started/using-the-api/#file-formats
     */
    format?: RenderImageFormat;

    /**
     * A CSS selector to target a specific element on the page.
     * The API will crop the image to the dimensions of this element.
     */
    selector?: string;

    /**
     * Adjusts the pixel ratio for the screenshot.
     * The default is 2, which is equivalent to a 4K monitor.
     */
    device_scale?: number;

    /**
     * Set the height of Chrome's viewport. This will disable automatic cropping.
     */
    viewport_height?: number;

    /**
     * Set the width of Chrome's viewport. This will disable automatic cropping.
     */
    viewport_width?: number;

    /**
     * Sets a limit on time to wait until the screenshot is taken.
     */
    max_wait_ms?: number;

    /**
     * Adds extra time before taking the screenshot, such as when waiting for JavaScript to execute.
     */
    ms_delay?: number;

    /**
     * Wait until ScreenshotReady() is called from JavaScript before taking the screenshot.
     */
    render_when_ready?: boolean;

    /**
     * Ensure the image is only ever rendered and saved one time.
     */
    max_render_once?: boolean;

    /**
     * Reuse an identical image created within this many seconds without consuming image credits.
     * HTML/CSS defaults vary by plan, while URL requests default to 0. Set to 0 to disable deduplication.
     * This applies only to standard single-image POST creation requests. It does not apply to image
     * batch requests and is not included in signed create-and-render URLs generated by the client.
     * @see https://docs.htmlcsstoimage.com/parameters/dedupe_duration_s/
     */
    dedupe_duration_s?: number;

    /**
     * HTML/CSS images use Twemoji by default; true disables it. URL images inject Twemoji only when explicitly false; omission or true leaves the page's emoji handling unchanged.
     */
    disable_twemoji?: boolean;

    /**
     * Render as if the user has selected light or dark mode.
     */
    color_scheme?: ColorSchemeType;

    /**
     * Set the browser timezone using an IANA timezone name.
     */
    timezone?: string;

    /**
     * Render as if the viewport is a mobile device.
     */
    viewport_mobile?: boolean;

    /**
     * Enable touch interactions within the viewport.
     */
    viewport_touch?: boolean;

    /**
     * Render the viewport in landscape orientation.
     */
    viewport_landscape?: boolean;

    /**
     * Set the rendering media type.
     */
    media_type?: MediaType;

    /**
     * Select an organization proxy for rendering.
     */
    proxy_id?: string;

    /** Block matching browser network requests. Requires a paid plan. */
    request_overrides?: RequestOverride[];

    /**
     * Save rendered images to one of the organization's configured storage destinations.
     */
    storage_destination_id?: string;

    /**
     * Set the maximum width in jumbo mode. jumbo_max_height must also be defined.
     */
    jumbo_max_width?: number;

    /**
     * Set the maximum height in jumbo mode. jumbo_max_width must also be defined.
     */
    jumbo_max_height?: number;

    /**
     * Render the image with a transparent background.
     */
    transparent_background?: boolean;

    /**
     * Options for generating a PDF from the HTML/CSS or Url.
     */
    pdf_options?: PDFOptions;

    protected constructor(init?: Partial<BaseCreateImageRequest>) {
        Object.assign(this, init);
    }
}


export class CreateHtmlCssImageRequest extends BaseCreateImageRequest {
    readonly __type = 'html_css' as const;
    /**
     * Represents an HTML string value that should contain raw HTML content.
     */
    html!: string;
    /**
     * A variable representing optional CSS styles.
     * This can be used to define custom styling rules that are applied to a component or element.
     * The value should be a valid CSS string or undefined.
     */
    css?: string;
    /**
     * An optional array of strings representing the names of Google Fonts to be used in the application.
     *
     * This variable allows specifying one or more Google Fonts that can be dynamically loaded for styling purposes.
     * Each entry in the array should be the name of a valid font available from Google Fonts.
     *
     * If undefined or empty, no Google Fonts will be loaded.
     */
    google_fonts?: string[];

    constructor(init?: Partial<CreateHtmlCssImageRequest>) {
        super();
        Object.assign(this, init);
    }
}

export class CreateUrlImageRequest extends BaseCreateImageRequest {
    readonly __type = 'url' as const;
    /**
     * Represents a web address or resource location.
     * This variable is expected to contain a valid URL string.
     */
    url!: string;

    /**
     * Custom CSS rules to inject into the target webpage before rendering.
     * Use this to override existing styles or customize specific elements.
     */
    css?: string;

    /**
     * Custom HTTP headers for top-level requests to the requested URL's origin
     * and any additional_header_origins.
     * @see https://docs.htmlcsstoimage.com/parameters/headers/
     */
    headers?: Record<string, string>;

    /**
     * Additional exact HTTP or HTTPS origins allowed to receive custom headers.
     * @see https://docs.htmlcsstoimage.com/parameters/headers/#additional-header-origins
     */
    additional_header_origins?: string[];

    /**
     * Also send custom headers with subrequests to allowed origins.
     * @see https://docs.htmlcsstoimage.com/parameters/headers/#include-headers-on-subrequests
     */
    include_headers_on_subrequests?: boolean;

    /**
     * Add X-HCTI-SCREENSHOT: 1 to the top-level page request.
     * @see https://docs.htmlcsstoimage.com/parameters/identify_as_hcti/
     */
    identify_as_hcti?: boolean;

    /**
     * Indicates whether the screenshot should capture the entire webpage in full height.
     *
     * When set to true, this property ensures that the screenshot includes the full vertical content of the webpage,
     * scrolling beyond the visible portion of the viewport if necessary. If set to false or null, only the visible
     * portion of the webpage within the configured viewport dimensions will be captured.
     */
    full_screen?: boolean;

    /**
     * Attempt to block cookie/consent banners from displaying.
     */
    block_consent_banners?: boolean;

    constructor(init?: Partial<CreateUrlImageRequest>) {
        super();
        Object.assign(this, init);
    }
}

export class CreateTemplatedImageRequest<T = Record<string, any>> {
    readonly __type = 'templated' as const;
    /**
     * The file format used in the URL returned by the image creation request.
     *
     * This only changes the extension of the initially returned URL; it does
     * not change the stored image definition or prevent the image from being
     * rendered in another supported format. When omitted, the API returns its
     * default image URL.
     *
     * @see https://docs.htmlcsstoimage.com/getting-started/using-the-api/#file-formats
     */
    format?: RenderImageFormat;

    /**
     * Identifies the specific template to be used.
     */
    template_id!: string;

    /**
     * The optional version of the template to be used. If not provided, the most recent version is used.
     */
    template_version?: number;

    /**
     * Dynamic data to be injected into the template.
     */
    template_values!: T;

    constructor(init?: Partial<CreateTemplatedImageRequest<T>>) {
        Object.assign(this, init);
    }
}

/** Shared defaults or one variation in a templated image batch. */
export class TemplatedBatchImageOptions<T = Record<string, any>> {
    /** Omit to inherit the default template. Supplying an ID resets the inherited version. */
    template_id?: string;
    /** Inherits the default version, or uses latest when a template_id is supplied. */
    template_version?: number;
    /** Objects merge recursively; arrays, scalars, and explicit null values replace defaults. */
    template_values?: T;
    /** File format of the returned URL; omitted values inherit the default format. */
    format?: RenderImageFormat;

    constructor(init?: Partial<TemplatedBatchImageOptions<T>>) {
        Object.assign(this, init);
    }
}

/**
 * Shared browser settings and timeline options for recording HTML/CSS or a URL.
 * Optional settings use the API defaults.
 * @see https://docs.htmlcsstoimage.com/getting-started/recordings/
 */
export abstract class BaseCreateRecordingRequest {
    /**
     * Requested duration in milliseconds: 500–30000, or up to 90000 in target mode.
     * duration_mode controls how actions fit into this duration.
     * @see https://docs.htmlcsstoimage.com/parameters/duration_ms/
     */
    duration_ms!: number;
    /**
     * CSS to style HTML content or inject into a URL page after it loads.
     * @see https://docs.htmlcsstoimage.com/parameters/css/
     */
    css?: string | null;
    /**
     * Capture pixel density. Defaults to 2 for HTML/CSS and 1 for URL recordings.
     * @see https://docs.htmlcsstoimage.com/parameters/device_scale/
     */
    device_scale?: number | null;
    /**
     * Viewport height in CSS pixels. Supply both dimensions to set the recording size.
     * @see https://docs.htmlcsstoimage.com/parameters/viewport/
     */
    viewport_height?: number | null;
    /**
     * Viewport width in CSS pixels. Supply both dimensions to set the recording size.
     * @see https://docs.htmlcsstoimage.com/parameters/viewport/
     */
    viewport_width?: number | null;
    /**
     * Disable Twemoji for HTML/CSS when true. URL recordings inject it only when explicitly false.
     * @see https://docs.htmlcsstoimage.com/parameters/disable_twemoji/
     */
    disable_twemoji?: boolean | null;
    /**
     * Reuse an identical recording created within this many seconds. Set to 0 to disable deduplication.
     * @see https://docs.htmlcsstoimage.com/parameters/dedupe_duration_s/
     */
    dedupe_duration_s?: number | null;
    /**
     * Chrome's preferred light or dark color scheme while recording.
     * @see https://docs.htmlcsstoimage.com/parameters/color_scheme/
     */
    color_scheme?: ColorSchemeType | null;
    /**
     * Browser timezone as an IANA identifier, such as 'America/New_York'.
     * @see https://docs.htmlcsstoimage.com/parameters/timezone/
     */
    timezone?: string | null;
    /** Enable mobile viewport behavior, including the page's viewport meta tag.
     * @see https://docs.htmlcsstoimage.com/parameters/viewport/
     */
    viewport_mobile?: boolean | null;
    /** Emulate landscape orientation.
     * @see https://docs.htmlcsstoimage.com/parameters/viewport/
     */
    viewport_landscape?: boolean | null;
    /** Emulate a viewport that supports touch events.
     * @see https://docs.htmlcsstoimage.com/parameters/viewport/
     */
    viewport_touch?: boolean | null;
    /** CSS media type used while recording.
     * @see https://docs.htmlcsstoimage.com/parameters/media_type/
     */
    media_type?: MediaType | null;
    /** Organization proxy to use while recording.
     * @see https://docs.htmlcsstoimage.com/guides/advanced/proxies/
     */
    proxy_id?: string | null;
    /** Storage destination to receive the recording.
     * @see https://docs.htmlcsstoimage.com/guides/advanced/storage-destinations/
     */
    storage_destination_id?: string | null;
    /** Block matching browser requests while recording. Available on paid plans.
     * @see https://docs.htmlcsstoimage.com/parameters/request_overrides/
     */
    request_overrides?: RequestOverride[] | null;
    /** When recording and actions start after page preparation. Defaults to immediate.
     * @see https://docs.htmlcsstoimage.com/parameters/trigger/
     */
    trigger?: RecordingTrigger | null;
    /** Ordered interactions. Leave null or empty to record the page without interactions.
     * @see https://docs.htmlcsstoimage.com/parameters/actions/
     */
    actions?: RecordingAction[] | null;
    /** Optional MP4 or WebM soundtrack from an Asset Library ID or a public URL.
     * @see https://docs.htmlcsstoimage.com/parameters/audio/
     */
    audio?: RecordingAudio | null;
    /** Output format, frame rate, and scale. Defaults to MP4 at 30 fps.
     * @see https://docs.htmlcsstoimage.com/parameters/output/
     */
    output?: RecordingOutputOptions | null;
    /** How duration_ms limits the timeline. Defaults to at_most.
     * @see https://docs.htmlcsstoimage.com/parameters/duration_mode/
     */
    duration_mode?: RecordingDurationMode | null;
    /** Wait to render until media or storage is requested. Defaults to false; does not reset deduplicated recordings.
     * @see https://docs.htmlcsstoimage.com/parameters/defer_render/
     */
    defer_render?: boolean | null;
    /** Skip the preparation scroll that loads lazy content. Scrolling actions still run. Defaults to false.
     * @see https://docs.htmlcsstoimage.com/parameters/skip_scroll_preload/
     */
    skip_scroll_preload?: boolean | null;

    protected constructor(init?: Partial<BaseCreateRecordingRequest>) {
        Object.assign(this, init);
    }
}

